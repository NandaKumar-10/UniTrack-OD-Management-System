import React, { useState, useEffect } from 'react';
import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';

const AdminReports = () => {
  const [summaryData, setSummaryData] = useState(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const fetchSummary = async () => {
      try {
        const token = localStorage.getItem('token');
        const response = await fetch('http://localhost:5000/api/admin/summary', {
          headers: { 'Authorization': `Bearer ${token}` }
        });
        const data = await response.json();
        if (response.ok) {
          setSummaryData(data);
        }
      } catch (error) {
        console.error('Error fetching summary data:', error);
      } finally {
        setLoading(false);
      }
    };
    fetchSummary();
  }, []);

  const generatePDF = () => {
    if (!summaryData) return;
    
    const doc = new jsPDF();
    const currentDate = new Date().toLocaleDateString();

    // Title
    doc.setFontSize(22);
    doc.setTextColor(79, 70, 229); // Primary color
    doc.text('UniTrack Executive Summary', 14, 22);

    // Subtitle
    doc.setFontSize(14);
    doc.setTextColor(107, 114, 128);
    doc.text(`Department Activity Report - ${summaryData.period}`, 14, 32);

    // Generatation Date
    doc.setFontSize(10);
    doc.text(`Generated on: ${currentDate}`, 14, 40);

    // Table
    autoTable(doc, {
      startY: 50,
      head: [['Metric', 'Count']],
      body: [
        ['Events Conducted', summaryData.eventsCount],
        ['Student Achievements Logged', summaryData.achievementsCount],
        ['OD Applications Approved', summaryData.odsApprovedCount],
      ],
      headStyles: { fillColor: [79, 70, 229] },
      columnStyles: {
        0: { cellWidth: 100 },
        1: { cellWidth: 'auto', halign: 'center' },
      },
      theme: 'grid'
    });

    const finalY = doc.lastAutoTable.finalY || 50;

    // Footer
    doc.setFontSize(10);
    doc.setTextColor(150, 150, 150);
    doc.text('This document is auto-generated by UniTrack System.', 14, finalY + 20);

    doc.save(`UniTrack_Summary_${summaryData.period.replace(' ', '_')}.pdf`);
  };

  return (
    <div className="container fade-in">
      <h1 className="page-title">Monthly Reports</h1>
      <p className="page-subtitle">View and export high-level system activity metrics.</p>

      <div className="card" style={{ display: 'flex', flexDirection: 'column', maxWidth: '600px' }}>
        <h2 className="card-title">Monthly Activity Summary Module</h2>
        <p style={{ color: 'var(--text-muted)', marginBottom: '1.5rem', fontSize: '0.9rem' }}>
          Automatically collect data from events and student activities to generate a structured department highlights report.
        </p>

        <div style={{ background: 'var(--bg-color)', padding: '1.5rem', borderRadius: 'var(--radius-md)', border: '1px solid var(--border-color)', marginBottom: '1.5rem', flex: 1 }}>
          {loading ? (
            <div style={{ color: 'var(--text-muted)' }}>Loading summary data...</div>
          ) : summaryData ? (
            <>
              <div style={{ display: 'flex', justifyContent: 'space-between', marginBottom: '1rem' }}>
                <span style={{ fontWeight: 600 }}>Period: <span style={{ color: 'var(--primary)' }}>{summaryData.period}</span></span>
                <span className="badge badge-info" style={{ backgroundColor: 'var(--primary-light)', color: 'var(--primary)' }}>Ready to Generate</span>
              </div>
              <ul style={{ fontSize: '1rem', color: 'var(--text-main)', marginLeft: '1.5rem', marginBottom: '1rem', lineHeight: 2 }}>
                <li><strong>{summaryData.eventsCount}</strong> Events Conducted</li>
                <li><strong>{summaryData.achievementsCount}</strong> Student Achievements Logged</li>
                <li><strong>{summaryData.odsApprovedCount}</strong> OD Applications Approved</li>
              </ul>
            </>
          ) : (
             <div style={{ color: 'var(--text-muted)' }}>Error loading summary data.</div>
          )}
        </div>

        <button 
          onClick={generatePDF} 
          disabled={loading || !summaryData}
          className="btn btn-primary" 
          style={{ width: '100%', justifyContent: 'center' }}
        >
          {loading ? 'Processing...' : 'Generate & Download PDF Document'}
        </button>
      </div>
    </div>
  );
};

export default AdminReports;
